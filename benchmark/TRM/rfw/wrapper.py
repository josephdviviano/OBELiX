"""
Recurrent Foundation Wrapper (RFW).

A generic, domain-agnostic recurrent adapter that wraps a frozen
foundation model. Spiritually faithful to the Tiny Recursive Model
(TRM): persistent prediction (P) and reasoning (Z) states are updated
across H outer cycles and L inner cycles, with gradient flow only
through the final H-cycle (H-1 outer cycles run under no_grad).

Key ideas:
  - The frozen foundation model's weights are never modified
  - Adaptation happens via LoRA modules generated by hypernetworks
    conditioned on the current (P, Z) state — so the same frozen model
    is invoked differently at each H-cycle
  - Inside each H-cycle, the LoRAs are fixed while L-cycles refine Z
    by cross-attending to layer features captured from the frozen model
  - Option B (prediction via model): P is updated by a second frozen
    model pass with LoRAs conditioned on (P, refined-Z)

Domain specificity lives entirely in a FoundationAdapter the caller
provides. This wrapper knows nothing about crystals, proteins, etc.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Any

import torch
from torch import nn
from torch.utils.checkpoint import checkpoint

from .lora import CycleConditionalLoRA
from .cross_attn import CrossAttentionRefiner


# -- Domain-agnostic adapter interface ---------------------------------------

@dataclass
class LoRASite:
    """Specification for where a LoRA adapter should be installed.

    The adapter's hooks are responsible for looking up the LoRA by `name`
    and combining its delta with the frozen op's output. The default
    combination is output + delta; domain-specific combinations (e.g.,
    equivariance-preserving projections) are the adapter's responsibility.
    """
    name: str               # human-readable identifier (e.g., "block_3_attn_out")
    in_features: int        # input dim of the frozen op
    out_features: int       # output dim of the frozen op


class FoundationAdapter(ABC):
    """
    Abstract interface for plugging a foundation model into the RFW.

    Subclasses implement the domain-specific glue: identifying where to
    insert LoRA adapters inside the frozen model, running the model and
    extracting per-layer features, and domain-appropriate pooling.

    The wrapper treats the foundation model as an opaque nn.Module that
    takes a batch (whatever format the domain uses) and produces some
    output via its forward pass. The adapter's job is to install hooks
    that (a) inject LoRA deltas at specified sites and (b) capture
    intermediate layer features for the cross-attention refiner.
    """

    @abstractmethod
    def lora_sites(self) -> list[LoRASite]:
        """Return the list of sites where LoRA adapters should be installed."""
        ...

    @abstractmethod
    def install_hooks(self, frozen_model: nn.Module) -> None:
        """
        Register forward hooks that:
          1. Call the wrapper-provided LoRA at each site (adds delta to output)
          2. Capture per-layer features into self._captured_features
        Called once at wrapper init. The wrapper will later set the
        adapter's `_current_state` and `_loras` dict before each model call.
        """
        ...

    @abstractmethod
    def run_model(
        self,
        frozen_model: nn.Module,
        batch: Any,
        *,
        want_layer_features: bool = True,
    ) -> dict[str, torch.Tensor]:
        """
        Run the frozen foundation model on the batch. The captured layer
        features should be available in self._captured_features after this call.

        Args:
            want_layer_features: when False, the caller does not need
                `layer_features` / `key_padding_mask` (e.g. Option B's second
                pass only consumes `per_graph_pooled`). Adapters should skip
                allocating those tensors in that case.

        Returns a dict with:
          - 'layer_features': (B, L, N_max, F) — captured layer features,
            padded to N_max tokens per graph (only when want_layer_features=True)
          - 'key_padding_mask': (B, N_max) — True for padded positions
            (only when want_layer_features=True)
          - 'per_graph_pooled': (B, F) — final-layer features pooled to one
            vector per graph (always)
        """
        ...

    def set_state(self, P: torch.Tensor, Z: torch.Tensor) -> None:
        """Called by the wrapper before each model run to set the state
        that LoRA hypernetworks will condition on. Adapter implementations
        that need graph indexing for their LoRA hooks should also receive
        the graph index from the batch."""
        self._current_state = torch.cat([P, Z], dim=-1)

    def set_loras(self, loras: dict[str, CycleConditionalLoRA]) -> None:
        """Called once at wrapper init — gives adapter a reference to the
        LoRA modules so its hooks can find them by name."""
        self._loras = loras


# -- The wrapper -------------------------------------------------------------

@dataclass
class RFWConfig:
    state_dim: int = 64             # D — dim of P and Z
    H_cycles: int = 3               # outer recursion (only final has grad)
    L_cycles: int = 2               # inner refinement of Z per H-cycle
    # rank=4 → ~1.85M trainable LoRA params at 14 sites with C=128 (target).
    # rank=8 → ~3.7M (previous default; over the stated ~2M budget).
    # rank=16 → ~7.4M (for expressiveness experiments).
    lora_rank: int = 4
    cross_attn_heads: int = 4
    cross_attn_ffn_expansion: float = 2.0
    dropout: float = 0.0
    # Option B (True): P update runs the model again with LoRAs re-conditioned
    # on (P, refined-Z). Spiritually TRM-faithful, ~2x compute per H-cycle.
    # Option A (False): cheaper; P update consumes cat([pooled, Z]) so refiner
    # still has a gradient path. NOTE: changing this flag changes the shape of
    # the p_update Linear, so checkpoints are NOT compatible across the flag.
    prediction_via_model: bool = True
    use_l_cycle_checkpointing: bool = False
    # When True: initialize P/Z from a zero-LoRA frozen pass + learnable
    # projections of the pooled features (HRM-Text z_H⁰-from-embeddings idea).
    # When False: use learnable parameters P_init/Z_init (TRM convention).
    # Cost: one extra no-grad Equiformer pass per forward.
    init_from_input: bool = False
    # Max padded layer/token count — used to size the layer positional embedding
    max_layers: int = 32


class RecurrentFoundationWrapper(nn.Module):
    """
    Wrap a frozen foundation model with a lightweight recurrent adapter.

    Args:
        frozen_model:   the foundation model (already frozen by the caller)
        adapter:        domain-specific FoundationAdapter
        feature_dim:    F — dim of the per-layer features the adapter exposes
        cfg:            RFWConfig
    """

    def __init__(
        self,
        frozen_model: nn.Module,
        adapter: FoundationAdapter,
        feature_dim: int,
        cfg: RFWConfig | None = None,
    ):
        super().__init__()
        self.cfg = cfg or RFWConfig()
        D = self.cfg.state_dim

        # Store frozen model but do not register its params as trainable
        self.frozen_model = frozen_model
        for p in self.frozen_model.parameters():
            p.requires_grad_(False)

        self.adapter = adapter

        # Build LoRA modules at each site. state conditioning = concat(P, Z) → 2D
        self.loras = nn.ModuleDict()
        for site in adapter.lora_sites():
            self.loras[site.name] = CycleConditionalLoRA(
                in_features=site.in_features,
                out_features=site.out_features,
                rank=self.cfg.lora_rank,
                state_dim=2 * D,
            )

        # Give adapter a reference to the LoRAs so its hooks can find them
        adapter.set_loras(self.loras)
        adapter.install_hooks(self.frozen_model)

        # Cross-attention Z refiner
        self.refiner = CrossAttentionRefiner(
            state_dim=D,
            feature_dim=feature_dim,
            num_heads=self.cfg.cross_attn_heads,
            ffn_expansion=self.cfg.cross_attn_ffn_expansion,
            dropout=self.cfg.dropout,
            max_layers=self.cfg.max_layers,
        )

        # Initial states. Two paths:
        #   init_from_input=False (default, TRM convention): learnable params.
        #     At H_cycles>=2, the detach after the no_grad block severs their
        #     gradient path (1-step approximation). At H_cycles=1 they learn
        #     directly (see F2 fix in forward()).
        #   init_from_input=True (HRM-Text-inspired): no learnable init params;
        #     instead, P and Z are produced by learnable projections from the
        #     pooled features of a zero-LoRA frozen pass. Same training
        #     dynamics for the projection weights as for P_init/Z_init under
        #     the default path. Costs one extra no-grad foundation pass per
        #     forward.
        if self.cfg.init_from_input:
            self.p_init_proj = nn.Sequential(
                nn.LayerNorm(feature_dim), nn.Linear(feature_dim, D),
            )
            self.z_init_proj = nn.Sequential(
                nn.LayerNorm(feature_dim), nn.Linear(feature_dim, D),
            )
        else:
            self.P_init = nn.Parameter(torch.randn(1, D) * 0.02)
            self.Z_init = nn.Parameter(torch.randn(1, D) * 0.02)

        # P update head.
        # Option B (prediction_via_model=True): consumes pooled features from a
        # second frozen pass conditioned on (P, refined-Z). Refiner's gradient
        # path goes through that second pass.
        # Option A (prediction_via_model=False): no second pass; we must feed
        # the refined Z directly into p_update so the CrossAttentionRefiner has
        # a gradient path to the loss. Without this, the refiner is dead.
        if self.cfg.prediction_via_model:
            self.p_update = nn.Sequential(
                nn.LayerNorm(feature_dim),
                nn.Linear(feature_dim, D),
            )
        else:
            self.p_update = nn.Sequential(
                nn.LayerNorm(feature_dim + D),
                nn.Linear(feature_dim + D, D),
            )

        # Output head: scalar prediction from P
        self.head = nn.Sequential(
            nn.LayerNorm(D),
            nn.Linear(D, 1),
        )

    # -- core cycle -----------------------------------------------------------

    def _h_cycle_step(self, P: torch.Tensor, Z: torch.Tensor, batch: Any
                      ) -> tuple[torch.Tensor, torch.Tensor]:
        """One H-cycle: refine Z via L cycles, then update P."""

        # 1. Install LoRA state = concat(P, Z); run frozen model → layer features
        self.adapter.set_state(P, Z)
        outputs = self.adapter.run_model(self.frozen_model, batch)
        layer_features = outputs["layer_features"]          # (B, L, N_max, F)
        key_padding_mask = outputs["key_padding_mask"]      # (B, N_max)

        # 2. L-cycles: refine Z while LoRAs + layer_features are fixed
        def _refine_once(z_in):
            return self.refiner(z_in, layer_features, key_padding_mask)

        for _ in range(self.cfg.L_cycles):
            if self.cfg.use_l_cycle_checkpointing and torch.is_grad_enabled():
                Z = checkpoint(_refine_once, Z, use_reentrant=False)
            else:
                Z = _refine_once(Z)

        # 3. Update P — option B: run model again with LoRAs conditioned on (P, refined Z)
        if self.cfg.prediction_via_model:
            self.adapter.set_state(P, Z)
            # PASS 2 only consumes pooled features; skip layer_features padding.
            outputs_p = self.adapter.run_model(
                self.frozen_model, batch, want_layer_features=False,
            )
            pooled = outputs_p["per_graph_pooled"]           # (B, F)
            P = P + self.p_update(pooled)
        else:
            # Option A: feed refined Z alongside pooled features so the refiner
            # has a gradient path to the loss. p_update input is (F + D).
            P = P + self.p_update(
                torch.cat([outputs["per_graph_pooled"], Z], dim=-1)
            )

        return P, Z

    def forward(self, batch: Any) -> torch.Tensor:
        """
        Args:
            batch: whatever the adapter expects (domain-specific)
        Returns:
            predictions: (B,)
        """
        B = self._batch_size(batch)
        if self.cfg.init_from_input:
            # Run a frozen pass with zero LoRA state (delta=0 because hyper_B
            # is zero-init AND state has been LayerNormed; even at trained
            # state the explicit zero input still yields zero delta because
            # hyper_B output is multiplied with hyper_A output to form delta
            # and hyper_B(LN(0))=bias-only=0-init... safer to bypass via state).
            # We pass zero state to make the LoRA contribution trivially zero
            # in case hyper_B has trained away from zero.
            D = self.cfg.state_dim
            device = next(self.refiner.parameters()).device
            zero_P = torch.zeros(B, D, device=device)
            zero_Z = torch.zeros(B, D, device=device)
            self.adapter.set_state(zero_P, zero_Z)
            with torch.no_grad():
                outputs0 = self.adapter.run_model(
                    self.frozen_model, batch, want_layer_features=False,
                )
            pooled0 = outputs0["per_graph_pooled"]
            P = self.p_init_proj(pooled0)
            Z = self.z_init_proj(pooled0)
        else:
            P = self.P_init.expand(B, -1).contiguous()
            Z = self.Z_init.expand(B, -1).contiguous()

        # H_cycles - 1 outer iterations without gradients (TRM's 1-step gradient
        # approximation). The detach severs the link back to P_init/Z_init —
        # which is only meaningful if no_grad actually ran. At H_cycles=1 the
        # no_grad block executes zero iterations; detaching anyway would sever
        # P_init/Z_init from the loss for no reason, blocking the matched-LoRA
        # baseline where the inits should learn directly.
        if self.cfg.H_cycles > 1:
            with torch.no_grad():
                for _ in range(self.cfg.H_cycles - 1):
                    P, Z = self._h_cycle_step(P, Z, batch)
            P = P.detach()
            Z = Z.detach()

        # Final H-cycle with gradients
        P, Z = self._h_cycle_step(P, Z, batch)

        return self.head(P).squeeze(-1)

    def _batch_size(self, batch: Any) -> int:
        """Extract batch size from the batch.

        Adapters can override by implementing `batch_size(batch) -> int` —
        useful for domains where the batch object exposes neither
        `.num_graphs` (PyG) nor a `'batch_size'` key (dict)."""
        if hasattr(self.adapter, "batch_size"):
            return self.adapter.batch_size(batch)
        if hasattr(batch, "num_graphs"):
            return batch.num_graphs
        if isinstance(batch, dict) and "batch_size" in batch:
            return batch["batch_size"]
        if isinstance(batch, torch.Tensor) and batch.ndim >= 2:
            return batch.shape[0]
        raise ValueError(
            "Cannot determine batch size. Implement `batch_size(batch) -> int` "
            "on the FoundationAdapter, or pass a PyG Batch / dict with "
            "'batch_size' / 2D+ tensor."
        )

    # -- diagnostics ----------------------------------------------------------

    @property
    def num_trainable_params(self) -> int:
        return sum(p.numel() for p in self.parameters() if p.requires_grad)

    @property
    def num_frozen_params(self) -> int:
        return sum(p.numel() for p in self.frozen_model.parameters())

    def param_summary(self) -> str:
        lines = [f"Frozen: {self.num_frozen_params:,} params"]
        if self.cfg.init_from_input:
            init_params = (
                sum(p.numel() for p in self.p_init_proj.parameters())
                + sum(p.numel() for p in self.z_init_proj.parameters())
            )
            init_label = "P/Z init projections"
        else:
            init_params = self.P_init.numel() + self.Z_init.numel()
            init_label = "P/Z inits"
        trainable = {
            "LoRAs": sum(p.numel() for p in self.loras.parameters()),
            "CrossAttn refiner": sum(p.numel() for p in self.refiner.parameters()),
            init_label: init_params,
            "P update": sum(p.numel() for p in self.p_update.parameters()),
            "Head": sum(p.numel() for p in self.head.parameters()),
        }
        for name, n in trainable.items():
            lines.append(f"  {name}: {n:,}")
        lines.append(f"Total trainable: {self.num_trainable_params:,}")
        return "\n".join(lines)
